def ensure_column(cur, table: str, column: str, ddl: str) -> None:
    cur.execute(
        """
        SELECT 1
        FROM information_schema.columns
        WHERE table_name = %s AND column_name = %s
        """,
        (table, column),
    )
    if cur.fetchone() is None:
        cur.execute(f"ALTER TABLE {table} ADD COLUMN {column} {ddl}")


def create_schema(pg_conn) -> None:
    cur = pg_conn.cursor()

    # users additions required by current backend code
    ensure_column(cur, "users", "full_name", "TEXT")
    ensure_column(cur, "users", "email", "TEXT")
    ensure_column(cur, "users", "is_first_login", "BOOLEAN NOT NULL DEFAULT FALSE")
    # Preserve the original data model, which may store section names like BSIT-3A.
    cur.execute("ALTER TABLE users ALTER COLUMN section TYPE TEXT USING section::text")

    # token storage for remember-me / verification flows
    cur.execute(
        """
        CREATE TABLE IF NOT EXISTS user_tokens (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            token TEXT NOT NULL UNIQUE,
            expires_at TIMESTAMP NOT NULL,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
        """
    )
    cur.execute("CREATE INDEX IF NOT EXISTS idx_user_tokens_token ON user_tokens(token)")
    cur.execute("CREATE INDEX IF NOT EXISTS idx_user_tokens_user_id ON user_tokens(user_id)")

    # Part 2 tables
    cur.execute(
        """
        CREATE TABLE IF NOT EXISTS sections (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            teacher_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            name TEXT NOT NULL,
            school_year TEXT,
            semester TEXT,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
        """
    )

    cur.execute(
        """
        CREATE TABLE IF NOT EXISTS groups (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            section_id INTEGER NOT NULL REFERENCES sections(id) ON DELETE CASCADE,
            group_number INTEGER NOT NULL,
            group_name TEXT NOT NULL,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
        """
    )

    cur.execute(
        """
        CREATE TABLE IF NOT EXISTS students (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
            group_id INTEGER NOT NULL REFERENCES groups(id) ON DELETE CASCADE,
            stud_number TEXT NOT NULL,
            surname TEXT NOT NULL,
            first_name TEXT NOT NULL,
            middle_initial TEXT,
            email TEXT NOT NULL,
            temp_password TEXT,
            is_first_login BOOLEAN NOT NULL DEFAULT TRUE,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
        """
    )

    # record.student_id for student dashboard links
    ensure_column(cur, "record", "student_id", "INTEGER REFERENCES students(id) ON DELETE CASCADE")

    # Useful indexes for the live queries
    cur.execute("CREATE INDEX IF NOT EXISTS idx_sections_teacher_id ON sections(teacher_id)")
    cur.execute("CREATE INDEX IF NOT EXISTS idx_groups_section_id ON groups(section_id)")
    cur.execute("CREATE INDEX IF NOT EXISTS idx_students_group_id ON students(group_id)")
    cur.execute("CREATE INDEX IF NOT EXISTS idx_students_stud_number ON students(stud_number)")
    cur.execute("CREATE INDEX IF NOT EXISTS idx_students_email ON students(email)")
    cur.execute("CREATE INDEX IF NOT EXISTS idx_record_student_id ON record(student_id)")

    pg_conn.commit()
    cur.close()


def ensure_auto_id(pg_conn, table: str) -> None:
    cur = pg_conn.cursor()
    seq_name = f"{table}_id_seq"

    cur.execute(f"CREATE SEQUENCE IF NOT EXISTS {seq_name}")
    cur.execute(
        f"SELECT COALESCE(MAX(id), 0) FROM {table}"
    )
    max_id = cur.fetchone()[0] or 0
    cur.execute(f"SELECT setval(%s, %s, true)", (seq_name, max_id))
    cur.execute(
        f"ALTER TABLE {table} ALTER COLUMN id SET DEFAULT nextval(%s)",
        (seq_name,)
    )
    try:
        cur.execute(f"ALTER SEQUENCE {seq_name} OWNED BY {table}.id")
    except Exception:
        pass
    pg_conn.commit()
    cur.close()


def copy_table(sql_conn, pg_conn, table_name: str, columns: list[str], transform=None) -> int:
    src = sql_conn.cursor()
    src.execute(f"SELECT {', '.join(columns)} FROM {table_name}")
    rows = src.fetchall()
    if not rows:
        print(f"No rows found in {table_name}")
        return 0

    data = []
    for row in rows:
        values = [row[col] for col in columns]
        if transform:
            values = transform(row, values)
        data.append(tuple(values))

    placeholders = ",".join(["%s"] * len(columns))
    insert_sql = f"INSERT INTO {table_name} ({', '.join(columns)}) VALUES %s ON CONFLICT DO NOTHING"
    cur = pg_conn.cursor()
    execute_values(cur, insert_sql, data, template=None, page_size=100)
    pg_conn.commit()
    cur.close()
    print(f"Copied {len(data)} rows into {table_name}")
    return len(data)


def sqlite_table_exists(sql_conn, table_name: str) -> bool:
    cur = sql_conn.cursor()
    cur.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name=?", (table_name,))
    exists = cur.fetchone() is not None
    cur.close()
    return exists


