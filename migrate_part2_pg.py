def copy_record_with_student_id(sql_conn, pg_conn) -> None:
    if not sqlite_table_exists(sql_conn, "record"):
        print("No source record table found; skipping")
        return

    # Copy record rows and preserve student_id when available in source sqlite.
    src = sql_conn.cursor()
    src.execute("PRAGMA table_info(record)")
    record_cols = [r[1] for r in src.fetchall()]
    src.close()

    has_student_id = "student_id" in record_cols
    select_cols = ["id", "stud_id", "date", "type_of_undertaking", "total_score", "score", "remarks", "created_at", "updated_at"]
    if has_student_id:
        select_cols.insert(2, "student_id")

    cur = sql_conn.cursor()
    cur.execute(f"SELECT {', '.join(select_cols)} FROM record")
    rows = cur.fetchall()
    cur.close()

    data = []
    for row in rows:
        student_id = row["student_id"] if has_student_id else None
        data.append(
            (
                row["id"],
                row["stud_id"],
                row["date"],
                row["type_of_undertaking"],
                row["total_score"],
                row["score"],
                row["remarks"],
                row["created_at"],
                row["updated_at"],
                student_id,
            )
        )

    cur = pg_conn.cursor()
    execute_values(
        cur,
        "INSERT INTO record (id, stud_id, date, type_of_undertaking, total_score, score, remarks, created_at, updated_at, student_id) VALUES %s ON CONFLICT (id) DO NOTHING",
        data,
        template=None,
        page_size=100,
    )
    pg_conn.commit()
    cur.close()
    print(f"Copied {len(data)} rows into record")


def copy_sections_groups_students(sql_conn, pg_conn) -> None:
    for table_name in ["sections", "groups", "students"]:
        if not sqlite_table_exists(sql_conn, table_name):
            print(f"No source {table_name} table found; skipping copy for that table")

    # sections
    if sqlite_table_exists(sql_conn, "sections"):
        copy_table(sql_conn, pg_conn, "sections", ["id", "teacher_id", "name", "school_year", "semester", "created_at"])

    # groups
    if sqlite_table_exists(sql_conn, "groups"):
        copy_table(sql_conn, pg_conn, "groups", ["id", "section_id", "group_number", "group_name", "created_at"])

    # students
    if sqlite_table_exists(sql_conn, "students"):
        copy_table(
            sql_conn,
            pg_conn,
            "students",
            ["id", "user_id", "group_id", "stud_number", "surname", "first_name", "middle_initial", "email", "temp_password", "is_first_login", "created_at"],
            transform=lambda row, values: [
                values[0],
                values[1],
                values[2],
                values[3],
                values[4],
                values[5],
                values[6],
                values[7],
                values[8],
                bool(values[9]),
                values[10],
            ],
        )

    # user_tokens if source table exists
    if sqlite_table_exists(sql_conn, "user_tokens"):
        copy_table(sql_conn, pg_conn, "user_tokens", ["id", "user_id", "token", "expires_at", "created_at"])
    else:
        print("No source user_tokens table found; skipping")


def bump_sequences(pg_conn) -> None:
    cur = pg_conn.cursor()
    for table in ["users", "record", "sections", "groups", "students", "user_tokens"]:
        try:
            cur.execute(f"SELECT COALESCE(MAX(id), 0) FROM {table}")
            max_id = cur.fetchone()[0]
            cur.execute(f"SELECT pg_get_serial_sequence(%s, %s)", (table, "id"))
            seq = cur.fetchone()[0]
            if seq:
                cur.execute(f"SELECT setval(%s, %s, true)", (seq, max_id))
        except Exception:
            pg_conn.rollback()
    pg_conn.commit()
    cur.close()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--sqlite-file", required=True)
    parser.add_argument("--pg", default=os.environ.get("DATABASE_URL"))
    args = parser.parse_args()

    if not args.pg:
        print("Postgres connection string required: pass --pg or set DATABASE_URL")
        return 1

    sqlite_path = args.sqlite_file
    if not os.path.exists(sqlite_path):
        print(f"SQLite file not found: {sqlite_path}")
        return 1

    print(f"Opening sqlite: {sqlite_path}")
    sql_conn = sqlite3.connect(sqlite_path)
    sql_conn.row_factory = sqlite3.Row

    print("Connecting to Postgres")
    pg_conn = psycopg2.connect(args.pg)

    try:
        create_schema(pg_conn)
        ensure_auto_id(pg_conn, "users")
        ensure_auto_id(pg_conn, "record")
        copy_users(sql_conn, pg_conn)
        copy_record_with_student_id(sql_conn, pg_conn)
        copy_sections_groups_students(sql_conn, pg_conn)
        bump_sequences(pg_conn)
        print("Part 2 migration completed successfully")
        return 0
    finally:
        try:
            sql_conn.close()
        except Exception:
            pass
        try:
            pg_conn.close()
        except Exception:
            pass


if __name__ == "__main__":
    raise SystemExit(main())
